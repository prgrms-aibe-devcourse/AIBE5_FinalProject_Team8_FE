function pix(grid) {
  const n = grid.length;
  let r = '';
  grid.forEach((row, y) => {
    [...row].forEach((c, x) => {
      if (c === '1') r += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
    });
  });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${n} ${n}" shape-rendering="crispEdges" fill="#000">${r}</svg>`;
  return `url("data:image/svg+xml;utf8,${encodeURIComponent(svg)}")`;
}

export const ICO = Object.fromEntries(Object.keys(G).map(k => [k, pix(G[k])]));

/* 8×8 픽셀 아이콘. currentColor 마스크로 칠해진다. size 는 em 또는 px. */
export function RtIcon({ name, size, style, className = '' }) {
  const mask = ICO[name];
  if (!mask) return null;
  return (
    <span
      className={`rt-ico ${className}`}
      aria-hidden="true"
      style={{
        WebkitMaskImage: mask,
        maskImage: mask,
        ...(size ? { width: size, height: size } : null),
        ...style,
      }}
    />
  );
}
